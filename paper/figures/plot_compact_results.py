"""Select and render existing evidence for the six-page report; no experiments."""

import hashlib
import json
from pathlib import Path

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np
from plot_coverage import load, summarize, POLICIES, SETTINGS, LABELS

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
HOST_INPUT = ROOT / 'notes/experiment-evidence/host-dram-reported-results.json'
BLUE, GREEN, PURPLE = '#536e89', '#238269', '#8661a6'
plt.rcParams.update({
    'font.family': 'DejaVu Sans', 'font.size': 8, 'axes.titlesize': 8,
    'axes.labelsize': 8, 'xtick.labelsize': 7, 'ytick.labelsize': 7,
    'pdf.fonttype': 42, 'savefig.facecolor': 'white',
})


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    coverage, inputs = load()  # Verify frozen evidence, including the audit amendment.
    groups, _ = summarize(coverage)
    lines = [r'% Generated by plot_compact_results.py from the frozen 60-run study.',
             r'\begin{table}[t]', r'  \centering', r'  \small',
             r'  \setlength{\tabcolsep}{3pt}', r'  \begin{tabular}{lrrrr}',
             r'    \toprule', r'    & \multicolumn{2}{c}{FCFS} & \multicolumn{2}{c}{Prefix-aware} \\',
             r'    Setting & LRU & Predictive & LRU & Predictive \\', r'    \midrule']
    for setting, label in zip(SETTINGS, LABELS):
        values = [groups[setting, p]['mean_session_serving_s']['mean'] for p in POLICIES]
        cells = [f'{v:.2f}' if i != 2 else r'\textbf{' + f'{v:.2f}' + '}' for i, v in enumerate(values)]
        lines.append('    ' + label + ' & ' + ' & '.join(cells) + r' \\')
    lines += [r'    \bottomrule', r'  \end{tabular}',
              r'  \caption{Coverage mean session serving time (seconds), averaged over three repeats per cell. A10/A20/A30 are nested loads; B10/C10 are additional held-out cohorts. Bold denotes the lowest mean in each setting.}',
              r'  \label{tab:compact-coverage}', r'\end{table}']
    (HERE / 'compact-coverage-table.tex').write_text('\n'.join(lines) + '\n')

    host = json.loads(HOST_INPUT.read_text())
    assert host['host_kv_tokens'] * host['kv_bytes_per_token'] == 36 * 1024**3
    fig, axes = plt.subplots(1, 2, figsize=(7, 2.45),
                             gridspec_kw={'width_ratios': [1, 1.35]}, layout='constrained')
    x = np.arange(2)
    for delta, recovery, color in [(-.18, 'Recompute', BLUE), (.18, 'Host restore', GREEN)]:
        values = [r['session_s'] for r in host['primary_observations'] if r['recovery'] == recovery]
        bars = axes[0].bar(x + delta, values, width=.34, color=color, label=recovery)
        axes[0].bar_label(bars, labels=[f'{v:g}' for v in values], padding=3, fontsize=7)
    axes[0].set(title='(a) Recovery with LRU + FCFS fixed',
                xticks=x, xticklabels=['N = 28', 'N = 36'], ylim=(0, 1300),
                ylabel='Mean session serving time (s)')
    axes[0].legend(frameon=False, fontsize=7, loc='upper left')

    rows = host['n36_policy_observations']
    labels = ['LRU + FCFS', 'LRU + prefix', 'Predictive + prefix', '+ prefetch', '+ fetch-aware']
    colors = [BLUE, GREEN, '#aa96bd', '#c5b6d2', PURPLE]
    for y, (row, color) in enumerate(zip(rows, colors)):
        axes[1].barh(y, row['session_s'], height=.6, color=color)
        axes[1].text(5, y, f"{row['session_s']:g}", va='center', fontsize=7, color='white', fontweight='bold')
    for y, value in [(2, 175), (4, 135)]:
        axes[1].scatter(value, y, marker='D', s=23, facecolors='white', edgecolors='#242c37', zorder=4)
    axes[1].set(title='(b) Host-policy ablation, N = 36',
                yticks=np.arange(len(rows)), yticklabels=labels,
                xlabel='Mean session serving time (s)', xlim=(0, 255))
    axes[1].invert_yaxis()
    axes[1].scatter([], [], marker='D', s=20, facecolors='white', edgecolors='#242c37', label='Additional observation')
    axes[1].legend(loc='lower right', frameon=False, fontsize=6.5, bbox_to_anchor=(1, -.32))
    for ax, axis in zip(axes, ['y', 'x']):
        ax.grid(axis=axis, alpha=.18)
        ax.set_axisbelow(True)
        ax.spines[['top', 'right']].set_visible(False)
    fig.savefig(HERE / 'compact-host-results.pdf', bbox_inches='tight', metadata={'CreationDate': None, 'ModDate': None})
    fig.savefig(HERE / 'compact-host-results.png', bbox_inches='tight', dpi=230)
    plt.close(fig)
    outputs = [HERE / name for name in ['compact-coverage-table.tex', 'compact-host-results.pdf', 'compact-host-results.png']]
    inputs += [HOST_INPUT]
    provenance = {
        'scope': 'Existing evidence only; no new experiment or model run. Host values are rounded reported observations, not a raw-data re-audit. Diamonds identify the two additional observations, not confidence intervals.',
        'inputs': {str(p.relative_to(ROOT)): sha(p) for p in inputs},
        'script_sha256': sha(Path(__file__)),
        'outputs': {str(p.relative_to(ROOT)): sha(p) for p in outputs},
        'matplotlib_version': matplotlib.__version__, 'numpy_version': np.__version__,
    }
    (HERE / 'compact-figure-provenance.json').write_text(json.dumps(provenance, indent=2) + '\n')
    print('Rendered one compact table and one consolidated host figure from existing evidence.')


if __name__ == '__main__':
    main()
